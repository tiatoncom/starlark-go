//go:build ignore

// mkcasetables writes casetables.go: the static tables of the case maps (see
// casetab.go), from the package unicode of the Go that runs it. Run it with
// go generate in the directory of the package starlark, or with -o to write
// the file elsewhere.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode"
	"unicode/utf8"
)

const limit = 0x20000 // caseWidthLimit

// isCasedRune is that of library.go (TestCaseTables_... compares the tables
// made with it, so a difference is found).
func isCasedRune(r rune) bool {
	return 'a' <= r && r <= 'z' || 'A' <= r && r <= 'Z' || unicode.SimpleFold(r) != r
}

type bitset [limit / 64]uint64

func (b *bitset) set(r rune) { b[r>>6] |= 1 << (r & 63) }

func main() {
	out := flag.String("o", "casetables.go", "the file to write")
	flag.Parse()

	var upper, lower, title bitset
	var casedLower, casedTitle bitset
	for r := rune(0); r < limit; r++ {
		if utf8.RuneLen(unicode.ToUpper(r)) != utf8.RuneLen(r) {
			upper.set(r)
		}
		if utf8.RuneLen(unicode.ToLower(r)) != utf8.RuneLen(r) {
			lower.set(r)
		}
		if utf8.RuneLen(unicode.ToTitle(r)) != utf8.RuneLen(r) {
			title.set(r)
		}
		if r >= utf8.RuneSelf {
			if isCasedRune(unicode.ToLower(r)) {
				casedLower.set(r)
			}
			if isCasedRune(unicode.ToTitle(r)) {
				casedTitle.set(r)
			}
		}
	}
	// nothing beyond the limit has a case mapping
	for r := rune(limit); r <= unicode.MaxRune; r++ {
		if unicode.ToUpper(r) != r || unicode.ToLower(r) != r || unicode.ToTitle(r) != r {
			log.Fatalf("U+%04X has a case mapping beyond the limit %#x: raise caseWidthLimit", r, limit)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by mkcasetables.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package starlark\n\n")
	fmt.Fprintf(&b, "// caseTablesUnicodeVersion is the version of Unicode of package unicode when\n// the tables were generated.\n")
	fmt.Fprintf(&b, "const caseTablesUnicodeVersion = %q\n\n", unicode.Version)
	fmt.Fprintf(&b, "// generatedCaseWidths: see caseWidths (the words that are not 0 only).\n")
	fmt.Fprintf(&b, "var generatedCaseWidths = caseWidths{\n")
	for _, t := range []struct {
		name string
		set  *bitset
	}{{"upper", &upper}, {"lower", &lower}, {"title", &title}} {
		fmt.Fprintf(&b, "%s: ", t.name)
		writeBitset(&b, t.set)
		fmt.Fprintf(&b, ",\n")
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "// generatedCasedAfter: see isCasedAfter (the words that are not 0 only).\n")
	fmt.Fprintf(&b, "var generatedCasedAfter = [2][caseWidthLimit / 64]uint64{\n")
	for _, set := range []*bitset{&casedLower, &casedTitle} {
		writeBitset2(&b, set)
		fmt.Fprintf(&b, ",\n")
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// writeBitset writes [caseWidthLimit / 64]uint64{index: word, ...}.
func writeBitset(b *bytes.Buffer, s *bitset) {
	fmt.Fprintf(b, "[caseWidthLimit / 64]uint64{\n")
	for i, w := range s {
		if w != 0 {
			fmt.Fprintf(b, "%d: %#x,\n", i, w)
		}
	}
	fmt.Fprintf(b, "}")
}

// writeBitset2 is writeBitset for an element of a composite literal.
func writeBitset2(b *bytes.Buffer, s *bitset) {
	fmt.Fprintf(b, "{\n")
	for i, w := range s {
		if w != 0 {
			fmt.Fprintf(b, "%d: %#x,\n", i, w)
		}
	}
	fmt.Fprintf(b, "}")
}

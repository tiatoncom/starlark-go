func params(n int) string {
	s := ""
	for i := 0; i < n; i++ {
		if i > 0 {
			s += ", "
		}
		s += "p" + itoa(i) + "=0"
	}
	return s
}

func chain(n int) string {
	s := ""
	for i := 0; i < n-1; i++ {
		s += "def f" + itoa(i) + "(): return f" + itoa(i+1) + "()\n"
	}
	s += "def f" + itoa(n-1) + "(): return 1\n"
	return s
}

func itoa(i int) string {
	if i == 0 {
		return "0"
	}
	var b []byte
	for ; i > 0; i /= 10 {
		b = append([]byte{byte('0' + i%10)}, b...)
	}
	return string(b)
}

